defmodule Treeshake.ReachabilityTest do
  use ExUnit.Case, async: true

  @fixture Path.expand("../fixtures/treeshake_reachability", __DIR__)

  setup_all do
    input = Path.join(["tmp", inspect(__MODULE__), "input"])
    File.rm_rf!(input)

    %{ebin_files: compile_fixture(input)}
  end

  # Only start/2 of the application module is reached directly, the rest
  # through the other callbacks, on_load functions and struct building.
  @tag :tmp_dir
  test "application callbacks, on_load functions, NIF modules and structs", %{
    tmp_dir: tmp_dir,
    ebin_files: ebin_files
  } do
    output = Path.join(tmp_dir, "output")

    stats =
      Treeshake.run(
        ebin_files: ebin_files,
        output_dir: output,
        keep: [%{referenced_modules_defining: {:schema_marker, 0}}]
      )

    assert functions(output, :app_callbacks) == [prep_stop: 1, start: 2, stop: 1]
    assert functions(output, :callbacks_stop_dependency) == [stop: 0]

    # The on_load function is kept with what it calls
    assert functions(output, :on_load_module) == [init: 0, used: 0]

    # Loading NIFs requires their stubs, which nothing calls, so the ones
    # declared with -nifs are kept, or everything if there are none
    assert functions(output, :declared_nif_module) ==
             [init: 0, nif: 0, private_nif: 1, stub: 0, used: 0]

    assert functions(output, :nif_module) == [init: 0, nif_stub: 0, unused: 0, used: 0]

    assert functions(output, :on_load_dependency) == [init: 0, path: 0]

    # Spawned with erlang:spawn_opt/4 and erlang:spawn_monitor/3
    assert functions(output, :spawner) == [monitor_loop: 0, opt_loop: 0, start: 0]

    # The custom validator in a NimbleOptions schema
    assert functions(output, :options_schema) == [schema: 0, validate: 2]

    # Kernel.struct!/2 calls __struct__/1 of its module, Kernel.struct/2
    # __struct__/0
    assert functions(output, :struct_module) == [__struct__: 1]
    assert functions(output, :other_struct_module) == [__struct__: 0]

    # Functions generated by another module's macro, in a referenced module
    # implementing a behaviour, are kept: here, __generated__/0
    generated_impl = functions(output, GeneratedImpl)
    assert {:__generated__, 0} in generated_impl
    assert {:run, 0} in generated_impl
    refute {:unused, 0} in generated_impl

    # Kept whole for defining schema_marker/0 once referenced, though nothing
    # calls it, and removed if not referenced
    assert functions(output, :schema_like) == [other: 0, schema_marker: 0]
    assert :unreferenced_schema_like in stats.modules_removed
    assert :not_schema_like in stats.modules_removed
  end

  # Kernel and stdlib modules are left by default, even if unreachable, except
  # the ones tree-shaken like others
  @tag :tmp_dir
  test "modules left by default", %{tmp_dir: tmp_dir, ebin_files: ebin_files} do
    stdlib = Enum.map([:array, :queue], &to_string(:code.which(&1)))
    stats = Treeshake.run(ebin_files: ebin_files ++ stdlib, output_dir: tmp_dir)

    assert :array in stats.modules_removed
    refute :queue in stats.modules_removed
  end

  defp compile_fixture(input) do
    File.mkdir_p!(input)

    beams =
      for source <- Path.wildcard(Path.join(@fixture, "*.erl")) do
        {:ok, _module} =
          :compile.file(to_charlist(source), [:debug_info, outdir: to_charlist(input)])

        Path.join(input, Path.basename(source, ".erl") <> ".beam")
      end

    # Treeshaking reads the abstract code from debug info, which `mix test`
    # turns off
    debug_info = Code.get_compiler_option(:debug_info)
    Code.put_compiler_option(:debug_info, true)

    {:ok, _modules, _diagnostics} =
      Kernel.ParallelCompiler.compile_to_path(Path.wildcard(Path.join(@fixture, "*.ex")), input,
        return_diagnostics: true
      )

    Code.put_compiler_option(:debug_info, debug_info)

    app_file = Path.join(input, "reachability.app")
    File.cp!(Path.join(@fixture, "reachability.app"), app_file)

    [app_file | beams ++ Path.wildcard(Path.join(input, "Elixir.*.beam"))]
  end

  defp functions(output, module) do
    path = output |> Path.join("#{module}.beam") |> to_charlist()
    {:ok, {^module, chunks}} = :beam_lib.chunks(path, [:exports, :locals])

    (chunks[:exports] ++ chunks[:locals])
    |> Enum.reject(fn {name, _arity} -> name == :module_info end)
    |> Enum.sort()
  end
end
